"""Deterministic Markdown "architecture atlas" from a Reflection.

Same source tree -> byte-identical output. No timestamps, no absolute paths,
every list sorted with an explicit key. The atlas reuses the Reflection
keep / layer / group / display machinery so it never disagrees with the
diagrams that `to_system_map()` / `to_system()` produce.
"""
from __future__ import annotations

import ast
from collections import Counter
from pathlib import Path
from typing import TYPE_CHECKING

from pydantic import BaseModel, ConfigDict, Field

from sysatlas._reflection.metrics import ROOT_GROUP, compute_metrics
from sysatlas._reflection.layers import LAYER_ORDER, layer_rank

if TYPE_CHECKING:
    from sysatlas._reflection.parser import Module
    from sysatlas._reflection.reflection import Reflection

_ROOT_GROUP = ROOT_GROUP
_SIZE_BUCKETS = ((20, "xs"), (75, "s"), (200, "m"), (500, "l"))
_ADJACENCY_MIN = 3
_HOTSPOT_LIMIT = 10
_CYCLE_MEMBER_CAP = 12
_CYCLE_EDGE_CAP = 20
_MIN_GROUP_ROWS = 3
_REGEN_HINT = (
    "<!-- Generated by sysatlas Reflection.save_atlas(). Regenerate after any "
    "module / class / function add, remove, or rename. Do not edit by hand. -->"
)


def _dedupe_by_name(modules: "list[Module]") -> "list[Module]":
    """Collapse modules that share a dotted name (e.g. Rust `main.rs` + `lib.rs`
    both mapping to `crate`), keeping the larger one so metrics stay coherent."""
    best: dict[str, Module] = {}
    for m in modules:
        cur = best.get(m.name)
        if cur is None or (m.loc, m.path) > (cur.loc, cur.path):
            best[m.name] = m
    return list(best.values())


def _size_bucket(loc: int) -> str:
    for ceiling, name in _SIZE_BUCKETS:
        if loc < ceiling:
            return name
    return "xl"


class AtlasModule(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str
    display: str
    label: str
    """Short name for prose/tables — `display`, or a longer form when `display` collides."""
    group: str
    layer: str
    rel_path: str
    purpose: str
    size: str
    loc: int
    classes: list[str] = Field(default_factory=list)
    functions: list[str] = Field(default_factory=list)
    internal_deps: list[str] = Field(default_factory=list)
    fan_in: int
    fan_out: int
    unparsed: bool = False


class AtlasLayer(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str
    members: list[str] = Field(default_factory=list)


class AtlasCycle(BaseModel):
    model_config = ConfigDict(extra="forbid")

    members: list[str] = Field(default_factory=list)
    edges: list[str] = Field(default_factory=list)


class AtlasCrossPackage(BaseModel):
    model_config = ConfigDict(extra="forbid")

    src: str
    dst: str
    edges: int
    examples: list[str] = Field(default_factory=list)


class Atlas(BaseModel):
    """Structured backing model for the Markdown atlas. JSON via `model_dump_json()`."""
    model_config = ConfigDict(extra="forbid")

    title: str
    root: str
    language: str
    module_count: int
    unparsed_count: int
    edge_count: int
    package_count: int
    cycle_count: int
    truncated: bool
    max_modules: int
    layers: list[AtlasLayer] = Field(default_factory=list)
    modules: list[AtlasModule] = Field(default_factory=list)
    cross_package: list[AtlasCrossPackage] = Field(default_factory=list)
    cycles: list[AtlasCycle] = Field(default_factory=list)
    hotspots: list[str] = Field(default_factory=list)
    public_api: list[str] = Field(default_factory=list)

    def to_markdown(self) -> str:
        return _render_markdown(self)


def build_atlas_model(
    reflection: "Reflection", title: str = "", *, max_modules: int = 80
) -> Atlas:
    """Build the structured Atlas from a Reflection (does not render Markdown)."""
    kept = _dedupe_by_name(reflection._kept_modules())
    root_path = Path(reflection.graph.root)
    root_name = root_path.name or str(root_path)
    language = "rust" if any(m.package == "crate" for m in kept) else "python"

    metrics = compute_metrics(kept, reflection._group_for)
    mm = metrics.by_name()

    display_of = {m.name: reflection._display_name(m.name) for m in kept}
    label_of = _disambiguate(display_of)

    modules: list[AtlasModule] = []
    for m in sorted(kept, key=lambda m: m.name):
        try:
            rel = Path(m.path).relative_to(root_path).as_posix()
        except ValueError:
            rel = Path(m.path).name
        node = mm[m.name]
        modules.append(
            AtlasModule(
                name=m.name,
                display=display_of[m.name],
                label=label_of[m.name],
                group=reflection._group_for(m.name) or _ROOT_GROUP,
                layer=reflection._layer_for(m.name),
                rel_path=rel,
                purpose=m.doc,
                size=_size_bucket(m.loc),
                loc=m.loc,
                classes=list(m.classes),
                functions=list(m.functions),
                internal_deps=node.internal_deps,
                fan_in=node.fan_in,
                fan_out=node.fan_out,
                unparsed=m.unparsed,
            )
        )

    layers = _build_layers(modules)
    cross = [
        AtlasCrossPackage(src=e.src, dst=e.dst, edges=e.count, examples=list(e.examples))
        for e in metrics.cross_package
    ]
    cycles = _build_cycles(
        metrics.cycles,
        {m.name: m.label for m in modules},
        {m.name: m.internal_deps for m in modules},
    )
    hotspots = [
        m.name
        for m in sorted(
            modules, key=lambda m: (-(m.fan_in + m.fan_out), m.name)
        )
        if m.fan_in + m.fan_out > 0
    ][:_HOTSPOT_LIMIT]

    return Atlas(
        title=title or root_name,
        root=root_name,
        language=language,
        module_count=len(modules),
        unparsed_count=sum(1 for m in modules if m.unparsed),
        edge_count=metrics.edge_count,
        package_count=len({m.group for m in modules}),
        cycle_count=len(cycles),
        truncated=len(modules) > max_modules,
        max_modules=max_modules,
        layers=layers,
        modules=modules,
        cross_package=cross,
        cycles=cycles,
        hotspots=hotspots,
        public_api=_public_api(root_path),
    )


def build_atlas(
    reflection: "Reflection", title: str = "", *, max_modules: int = 80
) -> str:
    """Build the Markdown atlas string from a Reflection."""
    return build_atlas_model(reflection, title, max_modules=max_modules).to_markdown()


def _disambiguate(display_of: dict[str, str]) -> dict[str, str]:
    """Map dotted name -> a label that is unique across the kept set.

    Uses the plain display name where it is unique; otherwise the dotted name
    with the shared root package stripped, falling back to the full dotted name.
    """
    clashed = {d for d, n in Counter(display_of.values()).items() if n > 1}
    if not clashed:
        return dict(display_of)
    out: dict[str, str] = {}
    for name, display in display_of.items():
        if display not in clashed:
            out[name] = display
            continue
        stripped = ".".join(name.split(".")[1:]) or name
        out[name] = stripped
    if len(set(out.values())) < len(out):
        for name, display in display_of.items():
            if display in clashed:
                out[name] = name
    return out


def _build_layers(modules: list[AtlasModule]) -> list[AtlasLayer]:
    by_layer: dict[str, list[str]] = {}
    for m in modules:
        by_layer.setdefault(m.layer, []).append(m.label)
    ordered = sorted(by_layer, key=lambda name: (layer_rank(name), name))
    return [AtlasLayer(name=name, members=sorted(by_layer[name])) for name in ordered]


def _build_cycles(
    raw_cycles: list[list[str]],
    display: dict[str, str],
    deps: dict[str, list[str]],
) -> list[AtlasCycle]:
    out: list[AtlasCycle] = []
    for members in raw_cycles:
        member_set = set(members)
        edges = sorted(
            f"{display.get(a, a)} -> {display.get(b, b)}"
            for a in members
            for b in deps.get(a, [])
            if b in member_set
        )
        out.append(
            AtlasCycle(
                members=[display.get(x, x) for x in members],
                edges=edges,
            )
        )
    return out


def _public_api(root_path: Path) -> list[str]:
    init = root_path / "__init__.py"
    if not init.is_file():
        return []
    try:
        tree = ast.parse(init.read_text(encoding="utf-8", errors="replace"))
    except (SyntaxError, ValueError):
        return []
    for node in tree.body:
        if isinstance(node, ast.Assign):
            if not any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
                continue
            value = node.value
        elif isinstance(node, ast.AnnAssign):
            if not (isinstance(node.target, ast.Name) and node.target.id == "__all__"):
                continue
            value = node.value
        else:
            continue
        if isinstance(value, (ast.List, ast.Tuple)):
            return [
                el.value
                for el in value.elts
                if isinstance(el, ast.Constant) and isinstance(el.value, str)
            ]
    return []


def _render_markdown(atlas: Atlas) -> str:
    show_purpose = any(m.purpose for m in atlas.modules)
    show_symbols = any(m.classes or m.functions for m in atlas.modules)
    lines: list[str] = [
        f"# Architecture Atlas — {atlas.title}",
        "",
        _REGEN_HINT,
        "",
        "## Overview",
        "",
        f"- Modules: {atlas.module_count}"
        + (f" ({atlas.unparsed_count} unparsed)" if atlas.unparsed_count else ""),
        f"- Internal import edges: {atlas.edge_count}",
        f"- Packages: {atlas.package_count}",
        f"- Import cycles: {atlas.cycle_count}",
        f"- Language: {atlas.language}",
    ]
    by_group: dict[str, list[AtlasModule]] = {}
    for m in atlas.modules:
        by_group.setdefault(m.group, []).append(m)
    per_group_cap = max(_MIN_GROUP_ROWS, atlas.max_modules // max(1, len(by_group)))
    if atlas.truncated:
        lines.append(
            f"- Note: per-package tables truncated to the {per_group_cap} "
            f"most-coupled modules per package ({atlas.module_count} > "
            f"max_modules={atlas.max_modules})."
        )

    lines += ["", "## Layers", ""]
    for layer in atlas.layers:
        lines.append(
            f"- **{layer.name}** ({len(layer.members)}): " + ", ".join(layer.members)
        )

    lines += ["", "## Packages", ""]
    header = ["module"]
    if show_purpose:
        header.append("purpose")
    header += ["size"]
    if show_symbols:
        header.append("symbols")
    header += ["out", "in"]
    for group in sorted(by_group):
        members = sorted(
            by_group[group], key=lambda m: (-(m.fan_in + m.fan_out), m.name)
        )
        shown = members[:per_group_cap] if atlas.truncated else members
        shown = sorted(shown, key=lambda m: m.name)
        lines += [
            f"### {group} — {len(members)} module(s)",
            "",
            "| " + " | ".join(header) + " |",
            "|" + "|".join(["---"] * len(header)) + "|",
        ]
        for m in shown:
            row = [f"`{m.label}`"]
            if show_purpose:
                row.append(_cell(m.purpose))
            row.append(m.size)
            if show_symbols:
                syms = list(m.classes) + [f"{fn}()" for fn in m.functions]
                row.append(_cell(", ".join(syms)))
            row += [str(m.fan_out), str(m.fan_in)]
            lines.append("| " + " | ".join(row) + " |")
        if atlas.truncated and len(members) > len(shown):
            lines.append(f"_… and {len(members) - len(shown)} more_")
        lines.append("")

    lines += ["## Dependency structure", ""]
    if atlas.cross_package:
        lines += [
            "| from | to | edges | examples |",
            "|---|---|---|---|",
        ]
        for e in atlas.cross_package:
            lines.append(
                f"| {e.src} | {e.dst} | {e.edges} | {_cell('; '.join(e.examples))} |"
            )
    else:
        lines.append("_No cross-package imports._")
    lines.append("")
    adjacency = [
        m for m in atlas.modules if m.fan_in + m.fan_out >= _ADJACENCY_MIN
    ]
    if adjacency:
        lines.append("Module adjacency (fan-in + fan-out ≥ 3):")
        lines.append("")
        disp = {m.name: m.label for m in atlas.modules}
        for m in sorted(adjacency, key=lambda m: (-(m.fan_in + m.fan_out), m.name)):
            deps = ", ".join(disp.get(d, d) for d in m.internal_deps) or "—"
            lines.append(f"- **{m.label}** → {deps}")
        lines.append("")

    lines += ["## Import cycles", ""]
    if not atlas.cycles:
        lines.append("_None detected._")
    else:
        for i, cyc in enumerate(atlas.cycles, 1):
            members = cyc.members[:_CYCLE_MEMBER_CAP]
            suffix = "" if len(cyc.members) <= _CYCLE_MEMBER_CAP else ", …"
            lines.append(f"{i}. {', '.join(members)}{suffix}")
            for edge in cyc.edges[:_CYCLE_EDGE_CAP]:
                lines.append(f"   - {edge}")
            if len(cyc.edges) > _CYCLE_EDGE_CAP:
                lines.append(f"   - _… and {len(cyc.edges) - _CYCLE_EDGE_CAP} more edges_")
    lines.append("")

    lines += ["## Coupling hotspots", ""]
    if not atlas.hotspots:
        lines.append("_None._")
    else:
        lines += ["| module | fan-in | fan-out |", "|---|---|---|"]
        by_name = {m.name: m for m in atlas.modules}
        for name in atlas.hotspots:
            m = by_name[name]
            lines.append(f"| `{m.label}` | {m.fan_in} | {m.fan_out} |")
    lines.append("")

    lines += ["## Public API surface", ""]
    if atlas.public_api:
        for sym in atlas.public_api:
            lines.append(f"- `{sym}`")
    else:
        lines.append("_No `__all__` in the root package._")
    lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _cell(text: str, cap: int = 90) -> str:
    text = text.replace("|", "\\|").replace("\n", " ").strip()
    if len(text) > cap:
        text = text[: cap - 1].rstrip() + "…"
    return text or "—"
