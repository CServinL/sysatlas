"""Markdown rendering of an Atlas. Pure function of the model; no I/O."""
from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from sysatlas._reflection.atlas import Atlas, AtlasModule

_ADJACENCY_MIN = 3
_CYCLE_MEMBER_CAP = 12
_CYCLE_EDGE_CAP = 20
_MIN_GROUP_ROWS = 3
_COMPONENT_ROWS = 40
_ENTRY_ROWS = 40
_EXTERNAL_ROWS = 40
_MODEL_NAMES_PER_COMPONENT = 12
_ENV_ROWS = 40
_GAP_ITEMS = 30
_LIST_CELL_ITEMS = 6
_TIER_LINES = 30
_NAMES_PER_LINE = 20
_LIBRARY_ITEMS = 40
_DATA_MODEL_COMPONENTS = 30
_PATTERN_ROWS = 30
_VIOLATION_ROWS = 40
_LAYER_LINES = 20
_LAYER_MEMBERS = 30
_PACKAGE_GROUPS = 30
_CROSS_PACKAGE_ROWS = 40
_ADJACENCY_ROWS = 30
_ADJACENCY_NEIGHBORS = 12
_CYCLES_SHOWN = 20
_API_SYMBOLS = 60
_REGEN_HINT = (
    "<!-- Generated by sysatlas Reflection.save_atlas(). Regenerate after any "
    "module / class / function add, remove, or rename. Do not edit by hand. -->"
)
_STATE_MARK = {"stale": " (stale)", "unverified": " (unverified)"}


def render_markdown(atlas: "Atlas") -> str:
    """Render the atlas model as Markdown; the same model always gives the same text."""
    lines: list[str] = _overview(atlas)
    by_group: dict[str, list["AtlasModule"]] = {}
    for m in atlas.modules:
        by_group.setdefault(m.group, []).append(m)
    per_group_cap = max(_MIN_GROUP_ROWS, atlas.max_modules // max(1, len(by_group)))
    if atlas.truncated:
        lines.append(
            f"- Note: per-package tables truncated to the {per_group_cap} "
            f"most-coupled modules per package ({atlas.module_count} > "
            f"max_modules={atlas.max_modules}).",
        )
    lines += _components(atlas)
    lines += _component_dependencies(atlas)
    lines += _entry_points(atlas)
    lines += _external_systems(atlas)
    lines += _data_models(atlas)
    lines += _configuration(atlas)
    lines += _pattern_candidates(atlas)
    lines += _patterns(atlas)
    lines += _conformance(atlas)
    lines += _layers(atlas)
    lines += _packages(atlas, by_group, per_group_cap)
    lines += _dependency_structure(atlas)
    lines += _cycles(atlas)
    lines += _hotspots(atlas)
    lines += _public_api(atlas)
    lines += _gaps(atlas)
    return "\n".join(lines).rstrip() + "\n"


def _cell(text: str, cap: int = 90) -> str:
    """Single-line, length-capped table text; '—' when empty. Pipes are escaped by `_table`."""
    text = " ".join(text.split())
    if len(text) > cap:
        text = text[: cap - 1].rstrip() + "…"
    return text or "—"


def _names(items: list[str], cap: int = _LIST_CELL_ITEMS) -> str:
    if not items:
        return "—"
    shown = ", ".join(items[:cap])
    return shown + (f" +{len(items) - cap}" if len(items) > cap else "")


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    def esc(cell: str) -> str:
        return " ".join(cell.split()).replace("|", "\\|")

    return [
        "| " + " | ".join(header) + " |",
        "|" + "|".join(["---"] * len(header)) + "|",
        *("| " + " | ".join(esc(c) for c in r) + " |" for r in rows),
    ]


def _list(items: list[str], cap: int) -> str:
    """Comma-joined items, with the omitted count when over `cap`."""
    shown = ", ".join(items[:cap])
    return shown + (f", … +{len(items) - cap}" if len(items) > cap else "")


def _more(total: int, shown: int) -> list[str]:
    return [f"_… and {total - shown} more_"] if total > shown else []


def _overview(atlas: "Atlas") -> list[str]:
    lines = [
        f"# Architecture Atlas — {atlas.title}",
        "",
        _REGEN_HINT,
        "",
        "## Overview",
        "",
    ]
    if atlas.summary:
        lines += [atlas.summary, ""]
    lines += [
        f"- Modules: {atlas.module_count}"
        + (f" ({atlas.unparsed_count} unparsed)" if atlas.unparsed_count else ""),
        f"- Components: {len(atlas.components)}",
        f"- Internal import edges: {atlas.edge_count}",
        f"- Packages: {atlas.package_count}",
        f"- Import cycles: {atlas.cycle_count}",
        f"- Language: {atlas.language}",
    ]
    return lines


def _components(atlas: "Atlas") -> list[str]:
    lines = ["", "## Components", ""]
    lines.append(
        "A component is a cluster of modules that acts as one unit: modules that "
        "import each other in a cycle, share a package, or serve a single caller. "
        "Tier 0 is what nothing else depends on."
    )
    lines.append("")
    show_purpose = any(c.purpose for c in atlas.components)
    header = ["component", "tier", "layer", "modules", "roles"]
    if show_purpose:
        header.append("purpose")
    header += ["depends on", "external"]
    rows = []
    for c in atlas.components[:_COMPONENT_ROWS]:
        row = [
            f"`{c.name}`",
            str(c.tier),
            c.layer,
            f"{c.module_count} ({c.loc} loc)",
            _cell(", ".join(c.roles)),
        ]
        if show_purpose:
            row.append(_cell(c.purpose, 140) + _STATE_MARK.get(c.intent_state, ""))
        row += [_cell(_names(c.depends_on), 70), _cell(_names(c.external), 50)]
        rows.append(row)
    return lines + _table(header, rows) + _more(len(atlas.components), _COMPONENT_ROWS) + [""]


def _component_dependencies(atlas: "Atlas") -> list[str]:
    lines = ["## Component dependencies", ""]
    tiers: dict[int, list[str]] = {}
    for c in atlas.components:
        tiers.setdefault(c.tier, []).append(c.name)
    for tier in sorted(tiers)[:_TIER_LINES]:
        lines.append(f"- **tier {tier}**: {_list(sorted(tiers[tier]), _NAMES_PER_LINE)}")
    return lines + _more(len(tiers), _TIER_LINES) + [""]


def _entry_points(atlas: "Atlas") -> list[str]:
    lines = ["## Entry points", ""]
    if not atlas.entry_points:
        return lines + ["_None detected._", ""]
    rows = [[f"`{e.kind}`", f"`{e.module}`", e.component] for e in atlas.entry_points[:_ENTRY_ROWS]]
    return lines + _table(["entry", "module", "component"], rows) + _more(
        len(atlas.entry_points), _ENTRY_ROWS
    ) + [""]


def _external_systems(atlas: "Atlas") -> list[str]:
    lines = ["## External systems", ""]
    if atlas.external_systems:
        rows = [
            [e.kind, e.system, _cell(_names(e.used_by), 80)]
            for e in atlas.external_systems[:_EXTERNAL_ROWS]
        ]
        lines += _table(["kind", "system", "used by"], rows)
        lines += _more(len(atlas.external_systems), _EXTERNAL_ROWS)
    else:
        lines.append("_No databases, network services, or queues detected._")
    lines.append("")
    if atlas.libraries:
        lines += [
            "Other third-party libraries: "
            + _list([f"`{x}`" for x in atlas.libraries], _LIBRARY_ITEMS),
            "",
        ]
    return lines


def _data_models(atlas: "Atlas") -> list[str]:
    lines = ["## Data models", ""]
    if not atlas.data_models:
        return lines + ["_None detected._", ""]
    for entry in atlas.data_models[:_DATA_MODEL_COMPONENTS]:
        lines.append(
            f"- **{entry.component}** ({len(entry.models)}): "
            + _list(entry.models, _MODEL_NAMES_PER_COMPONENT)
        )
    return lines + _more(len(atlas.data_models), _DATA_MODEL_COMPONENTS) + [""]


def _configuration(atlas: "Atlas") -> list[str]:
    lines = ["## Configuration", ""]
    if not atlas.env_vars:
        return lines + ["_No environment variables read._", ""]
    rows = [
        [f"`{v.name}`", _cell(_names(v.modules), 80)] for v in atlas.env_vars[:_ENV_ROWS]
    ]
    return lines + _table(["environment variable", "read by"], rows) + _more(
        len(atlas.env_vars), _ENV_ROWS
    ) + [""]


def _pattern_candidates(atlas: "Atlas") -> list[str]:
    lines = [
        "## Pattern candidates",
        "",
        "_Found from structure alone. Each is a candidate to confirm by reading the source, "
        "not a verdict. State machine, dependency injection and middleware chain are not detected._",
        "",
    ]
    if not atlas.pattern_candidates:
        return lines + ["_None found._", ""]
    rows = [
        [c.name, _cell("; ".join(c.evidence), 200), _cell(_names(c.components), 80)]
        for c in atlas.pattern_candidates
    ]
    return lines + _table(["pattern", "evidence", "components"], rows) + [""]


def _patterns(atlas: "Atlas") -> list[str]:
    if not atlas.patterns:
        return []
    lines = [
        "## Architectural patterns",
        "",
        "_Written by hand or by an LLM from the intent overlay; not generated from imports._",
        "",
    ]
    for p in atlas.patterns[:_PATTERN_ROWS]:
        where = f" Components: {_list(p.components, _NAMES_PER_LINE)}." if p.components else ""
        lines.append(f"- **{p.name}** — {p.description}{where}")
    return lines + _more(len(atlas.patterns), _PATTERN_ROWS) + [""]


def _conformance(atlas: "Atlas") -> list[str]:
    c = atlas.conformance
    if c is None:
        return []
    lines = [
        "## Spec conformance",
        "",
        f"- Status: {'conforms' if c.ok else 'departs from the spec'}",
        f"- Modules claimed by the spec: {c.mapped_modules} of {atlas.module_count}",
    ]
    if c.violations:
        lines += ["", "Dependencies the spec does not allow:", ""]
        rows = [
            [v.kind, v.src, v.dst, str(v.count), _cell("; ".join(v.examples))]
            for v in c.violations[:_VIOLATION_ROWS]
        ]
        lines += _table(["rule", "from", "to", "edges", "examples"], rows)
        lines += _more(len(c.violations), _VIOLATION_ROWS)
    if c.unmapped_modules:
        shown = c.unmapped_modules[:_GAP_ITEMS]
        lines += [
            "",
            f"Modules no spec component claims ({len(c.unmapped_modules)}; imports to and from "
            "them are not checked): "
            + ", ".join(f"`{n}`" for n in shown)
            + (f", … +{len(c.unmapped_modules) - len(shown)}" if len(c.unmapped_modules) > len(shown) else ""),
        ]
    if c.empty_components:
        lines += ["", "Spec components with no modules: " + _list(c.empty_components, _GAP_ITEMS)]
    return lines + [""]


def _layers(atlas: "Atlas") -> list[str]:
    lines = ["## Layers", "", "_From the hints file or from module names; not derived from imports._", ""]
    for layer in atlas.layers[:_LAYER_LINES]:
        lines.append(
            f"- **{layer.name}** ({len(layer.members)}): " + _list(layer.members, _LAYER_MEMBERS)
        )
    return lines + _more(len(atlas.layers), _LAYER_LINES) + [""]


def _packages(
    atlas: "Atlas", by_group: dict[str, list["AtlasModule"]], per_group_cap: int
) -> list[str]:
    show_purpose = any(m.purpose for m in atlas.modules)
    show_symbols = any(m.classes or m.functions for m in atlas.modules)
    lines = ["## Packages", ""]
    header = ["module"]
    if show_purpose:
        header.append("purpose")
    header += ["role", "size"]
    if show_symbols:
        header.append("symbols")
    header += ["out", "in"]
    shown_groups = sorted(
        sorted(by_group, key=lambda g: (-len(by_group[g]), g))[:_PACKAGE_GROUPS]
    )
    for group in shown_groups:
        members = sorted(
            by_group[group], key=lambda m: (-(m.fan_in + m.fan_out), m.name)
        )
        shown = members[:per_group_cap] if atlas.truncated else members
        shown = sorted(shown, key=lambda m: m.name)
        rows = []
        for m in shown:
            row = [f"`{m.label}`"]
            if show_purpose:
                row.append(_cell(m.purpose))
            row += [m.role, m.size]
            if show_symbols:
                syms = list(m.classes) + [f"{fn}()" for fn in m.functions]
                row.append(_cell(", ".join(syms)))
            row += [str(m.fan_out), str(m.fan_in)]
            rows.append(row)
        lines += [f"### {group} — {len(members)} module(s)", "", *_table(header, rows)]
        if atlas.truncated and len(members) > len(shown):
            lines.append(f"_… and {len(members) - len(shown)} more_")
        lines.append("")
    hidden = [g for g in by_group if g not in shown_groups]
    if hidden:
        lines += [
            f"_… and {len(hidden)} more packages "
            f"({sum(len(by_group[g]) for g in hidden)} modules)_",
            "",
        ]
    return lines


def _dependency_structure(atlas: "Atlas") -> list[str]:
    lines = ["## Dependency structure", ""]
    if atlas.cross_package:
        rows = [
            [e.src, e.dst, str(e.edges), _cell("; ".join(e.examples))]
            for e in atlas.cross_package[:_CROSS_PACKAGE_ROWS]
        ]
        lines += _table(["from", "to", "edges", "examples"], rows)
        lines += _more(len(atlas.cross_package), _CROSS_PACKAGE_ROWS)
    else:
        lines.append("_No cross-package imports._")
    lines.append("")
    adjacency = [m for m in atlas.modules if m.fan_in + m.fan_out >= _ADJACENCY_MIN]
    if adjacency:
        lines += ["Module adjacency (fan-in + fan-out ≥ 3):", ""]
        disp = {m.name: m.label for m in atlas.modules}
        ranked = sorted(adjacency, key=lambda m: (-(m.fan_in + m.fan_out), m.name))
        for m in ranked[:_ADJACENCY_ROWS]:
            deps = _list([disp.get(d, d) for d in m.internal_deps], _ADJACENCY_NEIGHBORS) or "—"
            lines.append(f"- **{m.label}** → {deps}")
        lines += _more(len(ranked), _ADJACENCY_ROWS)
        lines.append("")
    return lines


def _cycles(atlas: "Atlas") -> list[str]:
    lines = ["## Import cycles", ""]
    if not atlas.cycles:
        lines.append("_None detected._")
    else:
        for i, cyc in enumerate(atlas.cycles[:_CYCLES_SHOWN], 1):
            members = cyc.members[:_CYCLE_MEMBER_CAP]
            suffix = "" if len(cyc.members) <= _CYCLE_MEMBER_CAP else ", …"
            lines.append(f"{i}. {', '.join(members)}{suffix}")
            for edge in cyc.edges[:_CYCLE_EDGE_CAP]:
                lines.append(f"   - {edge}")
            if len(cyc.edges) > _CYCLE_EDGE_CAP:
                lines.append(f"   - _… and {len(cyc.edges) - _CYCLE_EDGE_CAP} more edges_")
        lines += _more(len(atlas.cycles), _CYCLES_SHOWN)
    return lines + [""]


def _hotspots(atlas: "Atlas") -> list[str]:
    lines = ["## Coupling hotspots", ""]
    if not atlas.hotspots:
        return lines + ["_None._", ""]
    by_name = {m.name: m for m in atlas.modules}
    rows = [
        [f"`{by_name[n].label}`", str(by_name[n].fan_in), str(by_name[n].fan_out)]
        for n in atlas.hotspots
    ]
    return lines + _table(["module", "fan-in", "fan-out"], rows) + [""]


def _public_api(atlas: "Atlas") -> list[str]:
    lines = ["## Public API surface", ""]
    if atlas.public_api:
        lines += [f"- `{sym}`" for sym in atlas.public_api[:_API_SYMBOLS]]
        lines += _more(len(atlas.public_api), _API_SYMBOLS)
    else:
        lines.append("_No `__all__` in the root package._")
    return lines + [""]


def _gaps(atlas: "Atlas") -> list[str]:
    g = atlas.gaps
    lines = [
        "## Documentation gaps",
        "",
        "_What still needs to be written down. The sysatlas-document skill closes these._",
        "",
    ]
    fp = {c.name: c.fingerprint for c in atlas.components}
    empty = True

    def item(title: str, entries: list[str]) -> None:
        nonlocal empty
        if not entries:
            return
        empty = False
        shown = entries[:_GAP_ITEMS]
        extra = len(entries) - len(shown)
        lines.append(f"- {title} ({len(entries)}): " + ", ".join(shown) + (f", … +{extra}" if extra > 0 else ""))

    item("Modules without a docstring", [f"`{n}`" for n in g.modules_without_doc])
    item(
        "Public symbols without a docstring",
        [f"`{u.module}`: {', '.join(u.symbols)}" for u in g.undocumented_symbols],
    )
    item(
        "Components with no intent recorded",
        [f"`{n}` [{fp[n]}]" for n in g.components_without_intent],
    )
    item("Components whose intent is stale", [f"`{n}` [{fp[n]}]" for n in g.stale_intent])
    item("Intent entries for components that no longer exist", [f"`{n}`" for n in g.unknown_intent])
    if empty:
        lines.append("_None._")
    return lines + [""]
